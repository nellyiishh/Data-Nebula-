"""Builds a SYNTHETIC demo site so the frontend can work before real NISAR data is ready.

    uv run python -m pipeline.make_demo_site

The scene is invented: a reservoir that shrinks through the season (exposing mud flats)
and crop fields that are harvested one after another. It is served with source="demo",
and the UI must say so. Replace it with pipeline.prepare_nisar output for the submission.
"""

import datetime as dt
import math
from pathlib import Path

import numpy as np
from numpy.typing import NDArray

from app.core.config import Settings
from app.core.geo import lonlat_to_mercator, mercator_to_lonlat
from app.core.logging import configure_logging, get_logger
from app.features.sites.models import MercatorBounds
from app.features.sites.schemas import Acquisition, PointOfInterest
from pipeline.writer import SiteMeta, write_site

DEMO_SITE_ID = "demo-reservoir"
DEMO_CENTER = (72.88, 41.79)  # lon, lat: Toktogul Reservoir area, Kyrgyzstan
DEMO_EXTENT_KM = 30.0
# 12-day revisit like NISAR, skipping its permanent 27 Jul – 10 Aug 2026 data gap.
DEMO_DATES = (
    dt.date(2026, 6, 20),
    dt.date(2026, 7, 2),
    dt.date(2026, 7, 14),
    dt.date(2026, 7, 26),
    dt.date(2026, 8, 19),
    dt.date(2026, 8, 31),
    dt.date(2026, 9, 24),
    dt.date(2026, 10, 18),
    dt.date(2026, 11, 11),
)
LOOKS = 8  # speckle strength: more looks = smoother image

# Normalised scene coordinates: x and y run 0..1 across the image, y = 0 at the top.
LAKE_CENTER = (0.45, 0.5)
LAKE_AXES = (0.32, 0.22)
LAKE_SHRINK = 0.45  # fraction of the lake's area lost by the last date
FIELDS = [  # (x0, y0, x1, y1, harvest point in the season 0..1)
    (0.68, 0.10, 0.77, 0.22, 0.45),
    (0.79, 0.10, 0.88, 0.22, 0.60),
    (0.68, 0.25, 0.77, 0.37, 0.75),
    (0.79, 0.25, 0.88, 0.37, 0.90),
]

Grid = NDArray[np.float64]
log = get_logger("demo")


def build_demo_site(data_dir: Path, size: int = 320, seed: int = 7) -> Path:
    rng = np.random.default_rng(seed)
    yy, xx = np.mgrid[0:size, 0:size] / (size - 1)
    swath_edge = xx + 0.3 * yy > 1.22  # no-data corner, like the edge of a radar swath

    hh_layers, hv_layers = [], []
    for t in range(len(DEMO_DATES)):
        hh_db, hv_db = _scene(xx, yy, season=t / (len(DEMO_DATES) - 1))
        hh_layers.append(np.where(swath_edge, np.nan, _speckle(hh_db, rng)))
        hv_layers.append(np.where(swath_edge, np.nan, _speckle(hv_db, rng)))

    bounds = _bounds_around(DEMO_CENTER, DEMO_EXTENT_KM)
    meta = SiteMeta(
        id=DEMO_SITE_ID,
        name="Demo reservoir (synthetic data)",
        change_type="water",
        source="demo",
        acquisitions=[
            Acquisition(date=d, granule_id=None, band="L", polarizations=["HH", "HV"])
            for d in DEMO_DATES
        ],
        points_of_interest=_points_of_interest(bounds),
        attribution="Synthetic demo data generated by Data Nebula, not a real observation.",
    )
    return write_site(
        data_dir,
        meta,
        hh=np.stack(hh_layers).astype(np.float32),
        hv=np.stack(hv_layers).astype(np.float32),
        bounds_merc=bounds,
    )


def _scene(xx: Grid, yy: Grid, season: float) -> tuple[Grid, Grid]:
    """Noise-free backscatter (dB) for one date; season runs 0 (June) to 1 (November)."""
    hh = np.full(xx.shape, -9.0)
    hv = np.full(xx.shape, -16.0)

    full_lake = _ellipse(xx, yy, scale=1.0)
    lake = _ellipse(xx, yy, scale=1.0 - LAKE_SHRINK * season)
    exposed = full_lake & ~lake  # wet, smooth mud left behind as the water level drops
    hh[exposed], hv[exposed] = -13.0, -22.0
    hh[lake], hv[lake] = -23.0, -30.0  # calm water mirrors radar away: very dark

    for x0, y0, x1, y1, harvest_at in FIELDS:
        field = (xx >= x0) & (xx <= x1) & (yy >= y0) & (yy <= y1)
        standing = season < harvest_at
        # Standing crops scatter in many directions, which shows up strongly in HV.
        hh[field], hv[field] = (-8.0, -13.0) if standing else (-11.0, -21.0)
    return hh, hv


def _ellipse(xx: Grid, yy: Grid, scale: float) -> NDArray[np.bool_]:
    cx, cy = LAKE_CENTER
    ax, ay = LAKE_AXES
    return ((xx - cx) / ax) ** 2 + ((yy - cy) / ay) ** 2 < scale


def _speckle(db: Grid, rng: np.random.Generator) -> Grid:
    linear = 10 ** (db / 10) * rng.gamma(LOOKS, 1 / LOOKS, size=db.shape)
    return 10 * np.log10(linear)


def _bounds_around(center: tuple[float, float], extent_km: float) -> MercatorBounds:
    x, y = lonlat_to_mercator(*center)
    half = extent_km * 1000 / 2 / math.cos(math.radians(center[1]))  # ground km → Mercator m
    return (x - half, y - half, x + half, y + half)


def _at(bounds: MercatorBounds, nx: float, ny: float) -> tuple[float, float]:
    xmin, ymin, xmax, ymax = bounds
    return mercator_to_lonlat(xmin + nx * (xmax - xmin), ymax - ny * (ymax - ymin))


def _points_of_interest(bounds: MercatorBounds) -> list[PointOfInterest]:
    spots = [
        ("lake", "Open water all season", 0.45, 0.50, "Stays dark in every image."),
        ("shore", "Exposed shoreline", 0.73, 0.50, "Water in June, mud flats by autumn."),
        ("field", "Crop field", 0.82, 0.30, "HV drops sharply after harvest."),
    ]
    points = []
    for point_id, name, nx, ny, note in spots:
        lon, lat = _at(bounds, nx, ny)
        points.append(PointOfInterest(id=point_id, name=name, lon=lon, lat=lat, note=note))
    return points


def main() -> None:
    configure_logging()
    site_dir = build_demo_site(Settings().data_dir)
    log.info("Demo site written to %s", site_dir)


if __name__ == "__main__":
    main()
