// Generates the hero background: layered mountain ridges in the TRACE palette, written as a
// small SVG (no photo licence, sharp at any size). Deterministic: same seed, same picture.
// Run: node scripts/make-hero-mountains.mjs [seed]
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'public', 'brand', 'hero-mountains.svg')
const W = 1920
const H = 1080
const seed = Number(process.argv[2] ?? 7)

function rand(s) {
  let x = s >>> 0
  return () => (x = (x * 1664525 + 1013904223) >>> 0) / 2 ** 32
}

/** A ridge as y(x): a few sharp peaks plus small noise, sampled every `step` px. */
function ridge(r, base, amp, peaks, step = 6) {
  const ps = Array.from({ length: peaks }, () => ({
    c: r() * W * 1.2 - W * 0.1,
    h: amp * (0.45 + r() * 0.55),
    w: 160 + r() * 360,
    p: 1.3 + r() * 0.8,
  }))
  const ph = [r() * 6, r() * 6, r() * 6]
  const pts = []
  for (let x = 0; x <= W; x += step) {
    let lift = 0
    for (const k of ps) lift = Math.max(lift, k.h * Math.max(0, 1 - Math.abs(x - k.c) / k.w) ** k.p)
    const n = Math.sin(x / 37 + ph[0]) * 6 + Math.sin(x / 13 + ph[1]) * 3 + Math.sin(x / 5.3 + ph[2]) * 1.5
    pts.push([x, base - lift + n * (0.4 + lift / amp)])
  }
  return pts
}

const pathOf = (pts) => `M0 ${H} L${pts.map(([x, y]) => `${x} ${y.toFixed(1)}`).join(' L')} L${W} ${H} Z`

/** Snow cap: from the crest down to a ragged snow line, only where the crest is above it. */
function snowOf(pts, snowY, r) {
  const lower = pts.map(([x, y]) => [x, Math.max(y, snowY + Math.sin(x / 9) * 6 + (r() - 0.5) * 10)])
  const top = pts.map(([x, y]) => `${x} ${y.toFixed(1)}`).join(' L')
  const bottom = [...lower].reverse().map(([x, y]) => `${x} ${y.toFixed(1)}`).join(' L')
  return `M${top} L${bottom} Z`
}

const r = rand(seed)
// Far to near: further ridges are lighter and bluer (air between us and them).
const layers = [
  { base: 640, amp: 430, peaks: 5, fill: '#2b4652', snow: '#cfe3e6', snowOp: 0.55 },
  { base: 720, amp: 340, peaks: 6, fill: '#213847', snow: '#b9d3d8', snowOp: 0.35 },
  { base: 820, amp: 240, peaks: 7, fill: '#1a2d39' },
  { base: 910, amp: 160, peaks: 8, fill: '#15232e' },
  { base: 1000, amp: 110, peaks: 9, fill: '#111a22' },
]

let shapes = ''
layers.forEach((L) => {
  const pts = ridge(r, L.base, L.amp, L.peaks)
  // Mist rising from the valley behind this ridge.
  shapes += `<rect x="0" y="${L.base - L.amp * 0.55}" width="${W}" height="${L.amp * 0.7}" fill="url(#mist)"/>\n`
  shapes += `<path d="${pathOf(pts)}" fill="${L.fill}"/>\n`
  if (L.snow) {
    const top = Math.min(...pts.map((p) => p[1]))
    const snowY = top + (L.base - top) * 0.32
    shapes += `<path d="${snowOf(pts, snowY, r)}" fill="${L.snow}" opacity="${L.snowOp}"/>\n`
  }
})

const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" preserveAspectRatio="xMidYMax slice">
<!-- Generated by web/scripts/make-hero-mountains.mjs (seed ${seed}). Not a real place. -->
<defs>
  <linearGradient id="sky" x1="0" y1="0" x2="0" y2="1">
    <stop offset="0" stop-color="#0d151c"/>
    <stop offset="0.55" stop-color="#16303a"/>
    <stop offset="1" stop-color="#2a5a5c"/>
  </linearGradient>
  <linearGradient id="mist" x1="0" y1="0" x2="0" y2="1">
    <stop offset="0" stop-color="#8acdb4" stop-opacity="0"/>
    <stop offset="0.7" stop-color="#8acdb4" stop-opacity="0.10"/>
    <stop offset="1" stop-color="#8acdb4" stop-opacity="0"/>
  </linearGradient>
  <radialGradient id="glow" cx="0.72" cy="0.38" r="0.5">
    <stop offset="0" stop-color="#8acdb4" stop-opacity="0.22"/>
    <stop offset="1" stop-color="#8acdb4" stop-opacity="0"/>
  </radialGradient>
</defs>
<rect width="${W}" height="${H}" fill="url(#sky)"/>
<rect width="${W}" height="${H}" fill="url(#glow)"/>
<!-- A satellite orbit: one thin arc, the radar's point of view. -->
<path d="M-100 380 Q 960 40 2020 300" fill="none" stroke="#42b6a8" stroke-opacity="0.22" stroke-width="2"/>
${shapes}</svg>
`

mkdirSync(dirname(OUT), { recursive: true })
writeFileSync(OUT, svg)
console.log(`Wrote ${OUT} (${(svg.length / 1024).toFixed(0)} KB, seed ${seed})`)
